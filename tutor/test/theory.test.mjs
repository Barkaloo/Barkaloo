 assert.equal((await theoryFile(new File(['%PDF-1.4\n'],'a.pdf'))).mime,'application/pdf');
 await assert.rejects(theoryFile(new File(['<html>'],'a.pdf')),/расширению/);
 await assert.rejects(theoryFile(new File(['<svg>'],'a.svg')),/формат/);
